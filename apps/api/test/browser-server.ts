import { mkdir,writeFile } from 'node:fs/promises';
import { createApp } from '../src/app.js';
import { config,prepareDatabase,resetFixtures,closePools } from './database.js';
import { memberFixture } from './member-fixtures.js';
import { PostgresMemberUnitOfWork } from '../src/platform/member-database.js';
import { MemberApplicationsService } from '../src/modules/applications/member-applications.service.js';
import { tokenHash } from '../src/modules/identity/identity.service.js';
import { owner,runtimePool } from './database.js';
import { randomBytes,randomUUID } from 'node:crypto';
await prepareDatabase();
const fixture=await resetFixtures();
const member=await memberFixture(fixture.officer.actor),otherMember=await memberFixture(fixture.officer.actor);
const memberApplications=new MemberApplicationsService(new PostgresMemberUnitOfWork(runtimePool),config.PRIVACY_NOTICE_VERSION);
const sample={purpose:'Fictional request awaiting staff assignment',requestedPrincipalCentavos:150_000,requestedTermMonths:6,currency:'PHP',noticeVersion:config.PRIVACY_NOTICE_VERSION,noticeAcknowledged:true};
const submitted=await memberApplications.create(member.actor,sample,randomUUID());
await memberApplications.submit(member.actor,submitted.id,{noticeVersion:config.PRIVACY_NOTICE_VERSION,acknowledgment:true},submitted.version,randomUUID());
const otherApplication=await memberApplications.create(otherMember.actor,{...sample,purpose:'Other member private request'},randomUUID());
config.PUBLIC_ORIGIN=`http://127.0.0.1:${process.env.AGAP_E2E_WEB_PORT??5174}`;
const uiLogout=randomBytes(32).toString('base64url');
await owner.query("INSERT INTO identity.sessions(id,token_hash,user_id,authenticated_at,methods,expires_at) VALUES($1,$2,$3,now(),$4,now()+interval '30 minutes')",[randomUUID(),tokenHash(uiLogout),fixture.administrator.actor.userId,['mfa']]);
const app=await createApp(config);
await app.listen(Number(process.env.AGAP_E2E_API_PORT??4101),'127.0.0.1');
await mkdir('.platform-test',{recursive:true});
await writeFile('.platform-test/browser.json',JSON.stringify({uiLogout,officer:fixture.officer.token,auditor:fixture.auditor.token,administrator:fixture.administrator.token,target:fixture.revocationTarget.token,organizationId:fixture.org,branchId:fixture.branch,member:member.token,memberId:member.record.id,otherMember:otherMember.token,otherMemberId:otherMember.record.id,otherApplicationId:otherApplication.id,submittedApplicationId:submitted.id}),{mode:0o600});
console.log('Fictional browser-test API ready.');
const stop=async()=>{await app.close();await closePools();process.exit(0);};
process.on('SIGTERM',()=>void stop());process.on('SIGINT',()=>void stop());
