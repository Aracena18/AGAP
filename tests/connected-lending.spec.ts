import { readFile, mkdir } from 'node:fs/promises';
import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
const origin=`http://127.0.0.1:${process.env.AGAP_E2E_WEB_PORT??5174}`;
test('actual separate staff review, unresolved notice, exact approval and reload through normal navigation',async({page,context,browser})=>{
  test.setTimeout(90000);
  const {connectedLending:f}=JSON.parse(await readFile('.platform-test/browser.json','utf8')) as {connectedLending:{appId:string;officer:string;reviewer:string}};
  await context.addCookies([{name:'agap_session',value:f.officer,url:origin,httpOnly:true,sameSite:'Lax'}]);
  const reviewerContext=await browser.newContext({baseURL:origin});
  try{
    await reviewerContext.addCookies([{name:'agap_session',value:f.reviewer,url:origin,httpOnly:true,sameSite:'Lax'}]);
    const reviewer=await reviewerContext.newPage();
    await reviewer.goto(`/#/staff/applications/${f.appId}/decision`);
    const reviewAttempts:{body:string|null;key:string|undefined}[]=[];let reviewLost=true;
    await reviewer.route(`**/api/v1/applications/${f.appId}/decision-review/conflicts`,async route=>{reviewAttempts.push({body:route.request().postData(),key:route.request().headers()['idempotency-key']});if(reviewLost){reviewLost=false;await route.fetch();await route.abort('failed');}else await route.continue();});
    await reviewer.getByRole('button',{name:'Declare own conflict status',exact:true}).click();
    await reviewer.getByLabel('Reason and evidence reviewed',{exact:true}).fill('Fictional reviewer self-declaration for the browser test.');
    await reviewer.getByRole('button',{name:'Record review action',exact:true}).click();
    await reviewer.getByRole('button',{name:'Retry same review submission',exact:true}).click();
    expect(reviewAttempts).toHaveLength(2);expect(reviewAttempts[1]).toEqual(reviewAttempts[0]);
    await expect(reviewer.getByText('Own conflict declaration: clear.',{exact:false})).toBeVisible();
    await page.goto('/#/staff/applications');
    await page.getByRole('row').filter({hasText:'Fictional connected lending journey'}).getByRole('link',{name:'Decision review',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Decision and explanation'})).toBeVisible();
    await page.getByRole('button',{name:'Declare own conflict status',exact:true}).click();
    await page.getByLabel('Reason and evidence reviewed',{exact:true}).fill('Fictional officer self-declaration for the browser test.');
    await page.getByRole('button',{name:'Record review action',exact:true}).click();
    await expect(page.getByRole('button',{name:'Confirm evidence check',exact:true})).toBeEnabled();
    const source=(await(await page.request.get(`/api/v1/applications/${f.appId}/evidence`)).json()).sources.find((s:{label:string})=>s.label.includes('income'));
    await page.getByRole('button',{name:'Raise a source concern',exact:true}).click();
    await page.getByLabel('Supporting source',{exact:true}).selectOption(source.id);
    await page.getByLabel('Exact supporting quotation',{exact:true}).fill(source.pages[0].text);
    await page.getByLabel('Concern and requested check',{exact:true}).fill('Check the fictional income cash-date statement.');
    await page.getByRole('button',{name:'Record review action',exact:true}).click();
    await expect(page.getByRole('button',{name:'Check concern',exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Check concern',exact:true}).click();
    await page.getByLabel('Reason and evidence reviewed',{exact:true}).fill('The source cash-date statement needs a separate documented review.');
    await page.getByRole('button',{name:'Record review action',exact:true}).click();
    await page.getByRole('button',{name:'Assign reviewer',exact:true}).click();
    await page.getByLabel('Separate eligible reviewer',{exact:true}).selectOption({label:'Fictional connected reviewer'});
    await page.getByLabel('Reason and evidence reviewed',{exact:true}).fill('Assign a separate fictional reviewer to inspect the statement.');
    await page.getByRole('button',{name:'Record review action',exact:true}).click();
    await expect(page.getByText('escalated review',{exact:true})).toBeVisible();
    await reviewer.getByRole('link',{name:'Review notices',exact:true}).click();
    await reviewer.getByRole('button',{name:'Acknowledge receipt',exact:true}).click();
    await expect(reviewer.getByText(/^Acknowledged /)).toBeVisible();
    await reviewer.getByRole('link',{name:'Open assigned application review',exact:true}).click();
    await expect(reviewer.getByText('escalated review',{exact:true})).toBeVisible();
    await expect(reviewer.getByRole('radio',{name:'Approve',exact:true})).toBeDisabled();
    await reviewer.getByRole('button',{name:'Record disposition',exact:true}).click();
    await reviewer.getByLabel('Review outcome',{exact:true}).selectOption('resolved');
    await reviewer.getByLabel('Reason and evidence reviewed',{exact:true}).fill('Inspected the exact fictional statement and dates; no source fact or financial rule was changed.');
    await reviewer.getByRole('button',{name:'Record review action',exact:true}).click();
    await expect(reviewer.getByText('resolved',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Refresh current basis',exact:true}).click();
    await page.getByRole('button',{name:'Confirm evidence check',exact:true}).click();
    await page.getByLabel('Reason and evidence reviewed',{exact:true}).fill('Inspected all sources, dated scenarios and the separate concern disposition.');
    await page.getByLabel('I inspected the complete current sources and all checked scenarios. This is a manual check.',{exact:true}).check();
    await page.getByRole('button',{name:'Record review action',exact:true}).click();
    await expect(page.getByText('Evidence check current',{exact:true})).toBeVisible();
    await page.getByLabel('Recommended offer',{exact:true}).selectOption({label:'Fictional principal-only two-month offer'});
    await page.getByLabel('Recommendation reason',{exact:true}).fill('Recommend the checked fictional principal-only offer after complete review.');
    await page.getByRole('button',{name:'Record recommendation',exact:true}).click();
    await expect(page.getByRole('status').filter({hasText:'Officer recommendation recorded'})).toBeVisible();
    await reviewer.getByRole('button',{name:'Refresh current basis',exact:true}).click();
    await reviewer.getByRole('radio',{name:'Approve',exact:true}).check();
    await reviewer.getByLabel('Offer considered',{exact:true}).selectOption({label:'Fictional principal-only two-month offer'});
    await reviewer.getByLabel('Decision rationale',{exact:true}).fill('Separate fictional reviewer inspected exact evidence, full horizon, costs and payment dates.');
    await reviewer.getByLabel('Next review date',{exact:true}).fill('2026-12-31');
    await reviewer.getByRole('button',{name:'Prepare exact preview',exact:true}).click();
    await expect(reviewer.getByText('Preview only. No decision has been recorded.',{exact:true})).toBeVisible();
    await reviewer.getByLabel('I reviewed this exact explanation and terms.',{exact:true}).check();
    const attempts:{body:string|null;key:string|undefined}[]=[];let lost=true;
    await reviewer.route(`**/api/v1/applications/${f.appId}/decisions`,async route=>{if(route.request().method()!=='POST'){await route.continue();return;}attempts.push({body:route.request().postData(),key:route.request().headers()['idempotency-key']});if(lost){lost=false;await route.fetch();await route.abort('failed');}else await route.continue();});
    await reviewer.getByRole('button',{name:'Record decision',exact:true}).click();
    await reviewer.getByRole('button',{name:'Retry the same submission',exact:true}).click();
    await expect(reviewer.getByRole('article',{name:'Saved decision brief'})).toBeVisible();
    expect(attempts).toHaveLength(2);expect(attempts[1]).toEqual(attempts[0]);
    await reviewer.reload();await expect(reviewer.getByRole('article',{name:'Saved decision brief'})).toBeVisible();
    await reviewer.getByRole('button',{name:'Inspect exact saved terms',exact:true}).click();
    await expect(reviewer.locator('pre').filter({hasText:'AGAP — exact reviewed terms'})).toBeVisible();
    await mkdir('docs/tasks/production/connected-lending-cl2/screenshots',{recursive:true});
    for(const width of [320,820,683,1366]){
      await reviewer.setViewportSize({width,height:900});expect(await reviewer.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
      expect((await new AxeBuilder({page:reviewer}).analyze()).violations).toEqual([]);
      await reviewer.screenshot({path:`docs/tasks/production/connected-lending-cl2/screenshots/saved-decision-${width}.png`,fullPage:true});
    }
  }finally{await reviewerContext.close();}
});
