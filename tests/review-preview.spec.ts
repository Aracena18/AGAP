test('real-record mode offers no scripted review and performs no private preview reads',async({page,context})=>{
 const fixture=JSON.parse(await readFile('.platform-test/browser.json','utf8')) as Record<string,string>;
 await context.addCookies([{name:'agap_member_session',value:fixture.uiAuditMember,url:origin,httpOnly:true,sameSite:'Lax'}]);
 let reads=0;
 await page.route('**/api/v1/member/session',async route=>{const response=await route.fetch();await route.fulfill({response,json:{...(await response.json()),recordMode:'real'}});});
 await page.route('**/api/v1/member/applications/*/workflow',async route=>{reads++;await route.continue();});
 await page.goto(`/#/member/applications/${fixture.submittedApplicationId}/analysis`);
 await expect(page.getByText('Demonstration analysis is available only in the fictional environment.',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Prepare review preview',exact:true})).toHaveCount(0);
 expect(reads).toBe(0);
 await signInStaff(context,'officer');
 await page.route('**/api/v1/session',async route=>{const response=await route.fetch();await route.fulfill({response,json:{...(await response.json()),recordMode:'real'}});});
 await page.goto('/#/staff/analysis-queue');
 await expect(page.getByText('Analysis queue requires authorized lending-review access in the fictional environment.',{exact:true})).toBeVisible();
 await expect(page.getByRole('navigation',{name:'Staff workspace'}).getByRole('link',{name:'Analysis queue',exact:true})).toHaveCount(0);
});
